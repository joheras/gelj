    private void jbFinishActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbFinishActionPerformed

        PleaseWait pw = new PleaseWait((JDialog) null, false);
        pw.setAlwaysOnTop(true);
        pw.toFront();
        String similarity = (String) jcbSimilarity.getSelectedItem();
        String linkage = (String) jcbLinkage.getSelectedItem();
        double tolerance = Double.parseDouble(jtfTolerance.getText());
        try {

            if (tolerance < 0) {
                JOptionPane.showMessageDialog(this, "Introduce a positive tolerance value", "", INFORMATION_MESSAGE, null);
                return;
            }

            DefaultListModel dmSelected = (DefaultListModel) jlSelected.getModel();
            DefaultListModel dmAvailable = (DefaultListModel) jlAvailable1.getModel();

            nc.setSelectedFields(new ArrayList<String>());
            nc.setNonSelectedFields(new ArrayList<String>());

            for (Object o : dmSelected.toArray()) {
                nc.getSelectedFields().add((String) o);
            }
            for (Object o : dmAvailable.toArray()) {
                nc.getNonSelectedFields().add((String) o);
            }

            if (nc.getSelectedFields().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Select at least a field to show in the dendrogram", "", INFORMATION_MESSAGE, null);
                return;
            }

            nc.setSimilaritymethod(similarity);
            nc.setLinkage(linkage);
            nc.setTolerance(tolerance);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Introduce a tolerance value", "", INFORMATION_MESSAGE, null);
            return;
        } catch (NullPointerException e) {
            JOptionPane.showMessageDialog(this, "Introduce a tolerance value", "", INFORMATION_MESSAGE, null);
            return;
        }

        Comparison c = nc.toComparison();
        dispose();
        if (edit) {
            updateComparison(c);

            try {

                if (jcbSimilarity.getSelectedIndex() > 4) {
                    int output = jcbOutput.getSelectedIndex();
                    if(output==2){
                        generateOcurrenceMatrix(c, nc.getSelectedFields());
                    }else{
                    if (output == 0) {
                        output = 1;
                    } else {
                        output = 3;
                    }
                    generateDendrogram(c, output, nc.getSelectedFields(), jCheckBox1.isSelected(), pw, jcbinvert.isSelected());
                }}
             else {
                    if (jcbOutput.getSelectedIndex() == 4) {
                        generateOcurrenceMatrix(c, nc.getSelectedFields());
                    } else {
                        generateDendrogram(c, jcbOutput.getSelectedIndex(), nc.getSelectedFields(), jCheckBox1.isSelected(), pw, jcbinvert.isSelected());
                    }
                }

            } catch (Exception ex) {
                Logger.getLogger(Step4.class.getName()).log(Level.SEVERE, null, ex);
            }

        } else {
            insertComparison(c);
            try {
                if (jcbSimilarity.getSelectedIndex() > 4) {
                    int output = jcbOutput.getSelectedIndex();
                    if(output==2){
                        generateOcurrenceMatrix(c, nc.getSelectedFields());
                    }else{
                    if (output == 0) {
                        output = 1;
                    } else {
                        output = 3;
                    }
                    generateDendrogram(c, output, nc.getSelectedFields(), jCheckBox1.isSelected(), pw, jcbinvert.isSelected());
                }}
             else {
                    if (jcbOutput.getSelectedIndex() == 4) {
                        generateOcurrenceMatrix(c, nc.getSelectedFields());
                    } else {
                        generateDendrogram(c, jcbOutput.getSelectedIndex(), nc.getSelectedFields(), jCheckBox1.isSelected(), pw, jcbinvert.isSelected());
                    }
                }
            } catch (Exception ex) {
                Logger.getLogger(Step4.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
        try {
            DefaultListModel dmSelected = (DefaultListModel) jlSelected.getModel();
            StandardUtils.save_comparisonconfig(similarity, linkage, tolerance, dmSelected.toArray());
        } catch (FileNotFoundException ex) {
            Logger.getLogger(Step4.class.getName()).log(Level.SEVERE, null, ex);
        } catch (UnsupportedEncodingException ex) {
            Logger.getLogger(Step4.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jbFinishActionPerformed

