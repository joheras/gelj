    private void jbNextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbNextActionPerformed

        if (nc.getSelectedExperiments().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Select at least an experiment", "", INFORMATION_MESSAGE, null);
        } else {

            nc.setMarkers(jcbincludemarkers.isSelected());
            
            
            
//            if(!allwithsamemarker(nc.getSelectedExperiments())){
//                JOptionPane.showMessageDialog(this, "All the selected experiments should be normalised using the same marker", "", INFORMATION_MESSAGE, null);
//                return;
//            }
            
            if(!edit || !initialexperiments.equals(nc.getSelectedExperiments()))
            {
                nc.setNonSelectedLanes(new ArrayList<LaneDB>());
            for (Experiment e : nc.getSelectedExperiments()) {
                ArrayList<LaneDB> lanes = getlanesexperiment(e.getId(), true);
                for (LaneDB l : lanes) {
                    if (jcbincludemarkers.isSelected()) {
                        nc.getNonSelectedLanes().add(l);
                    } else if (!l.isIsMarker()) {
                        nc.getNonSelectedLanes().add(l);
                    }
                }

            }
            
            }

            dispose();
            Step3 step3 = new Step3(nc,edit);
            step3.setVisible(true);
        }

    }//GEN-LAST:event_jbNextActionPerformed

