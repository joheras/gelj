    @Override
    public void tableChanged(TableModelEvent e) {
        
        int row = e.getFirstRow();
        int column = e.getColumn();
        Object cellValue = jtExperiments.getValueAt(row, column);
        
        
        if((boolean)cellValue){
            nc.getSelectedExperiments().add(nc.getNonSelectedExperiments().get(row));
        }else{
            nc.getSelectedExperiments().remove(nc.getNonSelectedExperiments().get(row));
        }
    }
