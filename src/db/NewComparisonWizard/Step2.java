    public void updateexperiments() {

        
        ArrayList<Experiment> experiments = nc.getNonSelectedExperiments();
        
        String[] names = {"Selected", "Experiment", "Date", "Author", "Marker", "Comments"};
        Object[][] data = new Object[experiments.size()][6];

        // We update the table
        for (int i = 0; i < experiments.size(); i++) {
            data[i][0] = nc.getSelectedExperiments().contains(experiments.get(i));
            data[i][1] = experiments.get(i).getName();
            data[i][2] = experiments.get(i).getDate().toString();
            data[i][3] = experiments.get(i).getUser().getUsername();
            data[i][4] = experiments.get(i).getMarker().getName();
            data[i][5] = experiments.get(i).getComments();
        }

        // Operations to change the model, we disable the edition of the date
        DefaultTableModel model = new DefaultTableModel(data, names) {
            public boolean isCellEditable(int rowIndex, int mColIndex) {
                if (mColIndex == 0) {
                    return true;
                } else {
                    return false;
                }
            }
            
            public Class getColumnClass(int columnIndex) {
                if (columnIndex == 0) {
                    return java.lang.Boolean.class;
                } else {
                    return java.lang.Object.class;
                }

            }
        };
        model.addTableModelListener(this);
        jtExperiments.setModel(model);

    }
    
    
    
