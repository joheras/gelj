    private ArrayList<String> getXSLTs(){
        ArrayList<String> xslts = new ArrayList<String>();
        String workingdir = System.getProperty("user.dir") + "/xslts/";
 
        File directory = new File(workingdir);
        String[] files = directory.list();
        int nFiles = files.length;
        if (nFiles != 0) {
            for (int i = 0; i < nFiles; i++) {
                if (files[i].contains(".xsl")) //encuentra los archivos .xls y almacena su ruta de acceso
                {
                    String name = files[i].substring(0, files[i].indexOf('.'));
                    xslts.add(name);
                }
            }
        }
        
        return xslts;
    }

    public void updatexslts(ArrayList<String> xslts) {

        String[] names = {"Selected", "Format"};

        Object[][] data = new Object[xslts.size()][names.length];

        // We update the table
        for (int i = 0; i < xslts.size(); i++) {
            data[i][0] = false;
            data[i][1] = xslts.get(i);
        }

        // Operations to change the model, we disable the edition of the date
        DefaultTableModel model = new DefaultTableModel(data, names) {
            public boolean isCellEditable(int rowIndex, int mColIndex) {
                if (mColIndex == 0) {
                    return true;
                } else {
                    return false;
                }
            }

            public Class getColumnClass(int columnIndex) {
                if (columnIndex == 0) {
                    return java.lang.Boolean.class;
                } else {
                    return java.lang.Object.class;
                }

            }
        };

        model.addTableModelListener(this);
        jtLanes.setModel(model);
        getRootPane().setDefaultButton(jbNext);
    }

