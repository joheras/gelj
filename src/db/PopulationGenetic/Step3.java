    public void updatelanes(ArrayList<LaneDB> newlanes) {

        String[] names = {"Selected", "Genus", "Species", "Strain Number", "Country", "MLST", "isMarker", "Experiment", "Comments"};

        Object[][] data = new Object[newlanes.size()][names.length];

        // We update the table
        for (int i = 0; i < newlanes.size(); i++) {
            data[i][0] = nc.getSelectedLanes().contains(newlanes.get(i));
            data[i][1] = newlanes.get(i).getGenus();
            data[i][2] = newlanes.get(i).getSpecies();
            data[i][3] = newlanes.get(i).getStrainNumber();
            data[i][4] = newlanes.get(i).getCountry();
            data[i][5] = newlanes.get(i).getMSLT();
            data[i][6] = newlanes.get(i).isIsMarker();
            data[i][7] = newlanes.get(i).getExperiment().getName();
            data[i][8] = newlanes.get(i).getComments();
        }

        // Operations to change the model, we disable the edition of the date
        DefaultTableModel model = new DefaultTableModel(data, names) {
            public boolean isCellEditable(int rowIndex, int mColIndex) {
                if (mColIndex == 0) {
                    return true;
                } else {
                    return false;
                }
            }

            public Class getColumnClass(int columnIndex) {
                if (columnIndex == 0) {
                    return java.lang.Boolean.class;
                } else {
                    return java.lang.Object.class;
                }

            }
        };

        model.addTableModelListener(this);
        jtLanes.setModel(model);
        getRootPane().setDefaultButton(jbNext);
    }

