    private void jbNextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbNextActionPerformed

        DefaultTableModel model = (DefaultTableModel) jtExperiments.getModel();

        ArrayList<Experiment> selectedexps = new ArrayList<>();

        for (int i = 0; i < model.getRowCount(); i++) {
            if ((boolean) model.getValueAt(i, 0)) {
                selectedexps.add(initialexperiments.get(i));
            }
        }

        if (!allwithsamemarker(selectedexps)) {
            JOptionPane.showMessageDialog(this, "All the selected experiments should be normalised using the same marker", "", INFORMATION_MESSAGE, null);
            return;
        }

        try {
            duplicateexperiments(selectedexps);
        } catch (IOException ex) {
            Logger.getLogger(ImportExperiment.class.getName()).log(Level.SEVERE, null, ex);
        }

        dispose();
        m.updateexperiments(true, true);


    }//GEN-LAST:event_jbNextActionPerformed

    private void duplicateexperiments(ArrayList<Experiment> exps) throws IOException {

        for (Experiment e : exps) {
            duplicateexperiment(e,studyid);
        }

    }

    public static void duplicateexperiment(Experiment e,int studyid) throws IOException {
        int expid = lastExperimentid();
        Experiment newexp = new Experiment(expid, "Copy-" + e.getName(), e.getDate(), e.getImagename(), e.getCalibrationMethod(), e.getComments(), getStudy(studyid), e.getMarker(), e.getUser());
        insertExperiment(newexp);

        File folderorigin = new File(System.getProperty("user.dir") + "/GelJDBImages/" + e.getStudy().getId() + "/" + e.getUser().getUsername() + "/experiments/" + e.getId() + "/");
        File imageorigin = new File(folderorigin + "/" + e.getImagename());

        File foldercopy = new File(System.getProperty("user.dir") + "/GelJDBImages/" + studyid + "/" + e.getUser().getUsername() + "/experiments/" + expid + "/");
        File imagedestine = new File(foldercopy + "/" + e.getImagename());

        foldercopy.mkdir();
        Files.copy(imageorigin.toPath(), imagedestine.toPath());

        //// Creation of the lanes to store them in the database
        // Creation of the folder where the lanes will be saved.
        File folderexplanes = new File(System.getProperty("user.dir") + "/GelJDBImages/" + studyid + "/" + e.getUser().getUsername() + "/experiments/" + expid + "/lanes/");
        folderexplanes.mkdir();

        // For each lane, we create a lanedb instance that is added to the database
        int laneid = lastLaneid();

        for (LaneDB l : getlanesexperiment(e.getId(), true)) {
            int lid = l.getId();
            LaneDB newlane = l;
            newlane.setId(laneid);
            newlane.setExperiment(newexp);
            insertLane(newlane);

            String folderoriginlane = System.getProperty("user.dir") + "/GelJDBImages/" + e.getStudy().getId() + "/" + e.getUser().getUsername() + "/experiments/" + e.getId() + "/lanes/" + lid + "/";
            String folderlanepath = System.getProperty("user.dir") + "/GelJDBImages/" + studyid + "/" + e.getUser().getUsername() + "/experiments/" + expid + "/lanes/" + laneid + "/";
            File folderlane = new File(folderlanepath);
            folderlane.mkdir();

            File curveorigin = new File(folderoriginlane + lid + ".curve");
            File curvedestiny = new File(folderlanepath + laneid + ".curve");
            Files.copy(curveorigin.toPath(), curvedestiny.toPath());

            File mworigin = new File(folderoriginlane + lid + ".mw");
            File mwdestiny = new File(folderlanepath + laneid + ".mw");
            Files.copy(mworigin.toPath(), mwdestiny.toPath());

            File bandsorigin = new File(folderoriginlane + lid + ".bands");
            File bandsdestiny = new File(folderlanepath + laneid + ".bands");
            Files.copy(bandsorigin.toPath(), bandsdestiny.toPath());
            
            File bandsorigin2 = new File(folderoriginlane + lid + ".bands2");
            File bandsdestiny2 = new File(folderlanepath + laneid + ".bands2");
            Files.copy(bandsorigin2.toPath(), bandsdestiny2.toPath());

            File imorigin = new File(folderoriginlane + lid + ".tiff");
            File imdestiny = new File(folderlanepath + laneid + ".tiff");
            Files.copy(imorigin.toPath(), imdestiny.toPath());

            File roiorigin = new File(folderoriginlane + lid + ".roi");
            File roidestiny = new File(folderlanepath + laneid + ".roi");
            Files.copy(roiorigin.toPath(), roidestiny.toPath());

            laneid++;
        }

    }


