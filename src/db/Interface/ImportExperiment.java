    public void updatetheexperiments() {

        initialexperiments = getExperimentsofOtherStudies(studyid);

        String[] names = {"Selected", "Experiment", "Date", "Author", "Marker", "Comments", "Study"};
        Object[][] data = new Object[initialexperiments.size()][7];

        // We update the table
        for (int i = 0; i < initialexperiments.size(); i++) {
            data[i][0] = false;
            data[i][1] = initialexperiments.get(i).getName();
            data[i][2] = initialexperiments.get(i).getDate().toString();
            data[i][3] = initialexperiments.get(i).getUser().getUsername();
            data[i][4] = initialexperiments.get(i).getMarker().getName();
            data[i][5] = initialexperiments.get(i).getComments();
            data[i][6] = initialexperiments.get(i).getStudy().getName();
        }

        // Operations to change the model, we disable the edition of the date
        DefaultTableModel model = new DefaultTableModel(data, names) {
            public boolean isCellEditable(int rowIndex, int mColIndex) {
                if (mColIndex == 0) {
                    return true;
                } else {
                    return false;
                }
            }

            public Class getColumnClass(int columnIndex) {
                if (columnIndex == 0) {
                    return java.lang.Boolean.class;
                } else {
                    return java.lang.Object.class;
                }

            }
        };
        jtExperiments.setModel(model);

    }

