    private void jbShowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbShowActionPerformed

        String similarity = (String) jcbSimilarity.getSelectedItem();
        double tolerance = 0;
        
        try{
            tolerance = Double.parseDouble(jtfTolerance.getText());
             if (tolerance < 0) {
                JOptionPane.showMessageDialog(this, "Introduce a positive tolerance value", "", INFORMATION_MESSAGE, null);
                return;
            }
         } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Introduce a tolerance value", "", INFORMATION_MESSAGE, null);
            return;
        } catch (NullPointerException e){
             JOptionPane.showMessageDialog(this, "Introduce a tolerance value", "", INFORMATION_MESSAGE, null);
            return;
        }
        int similarityhigher = Integer.parseInt(jtfSim.getText());

        ArrayList<LaneDB> lanes = null;

        if (jrbcurrent.isSelected()) {
            lanes = getLanes(lane.getExperiment().getStudy().getId());
        }

        if (jrbuser.isSelected()) {
            lanes = getUserLanes(lane.getExperiment().getStudy().getUser().getId());
        }

        if (jrball.isSelected()) {
            lanes = getAllLanes();
        }
        
        
        try {
            ArrayList<LaneDBwithsimilarity> res = computesimilarlanes(lane, lanes,similarity,tolerance,similarityhigher);
            
            
            if(res.isEmpty()){
                JOptionPane.showMessageDialog(this, "There is not any similar lane with these parameters", "", INFORMATION_MESSAGE, null);
            }else{
            dispose();
            ShowSimilarLanes ssl = new ShowSimilarLanes(res,lane);
            ssl.setVisible(true);}
        } catch (IOException ex) {
            Logger.getLogger(FindSimilarities.class.getName()).log(Level.SEVERE, null, ex);
        }
        

        
    }//GEN-LAST:event_jbShowActionPerformed


