    public InfoLane(LaneInfo l, boolean first, LaneManager lm) {
        initComponents();
        this.l = l;
        this.lm = lm;
        setDefaultCloseOperation(DISPOSE_ON_CLOSE);

        String[] locales = Locale.getISOCountries();
        ArrayList<String> countries = new ArrayList<>();
        for (String countryCode : locales) {
            Locale obj = new Locale("", countryCode);
            countries.add(obj.getDisplayCountry());
        }
        Collections.sort(countries);
        jcbCountry.addItem("");
        for (String country : countries) {
            jcbCountry.addItem(country);
        }

        jtfGenus.setText(l.getGenus());
        jtfSpecies.setText(l.getSpecies());
        jtfMSLT.setText(l.getMLST());
        jtfStrainNumber.setText("" + l.getStrainNumber());
        jcbCountry.setSelectedItem(l.getCountry());

        jCheckBox1.setSelected(first);

    }

