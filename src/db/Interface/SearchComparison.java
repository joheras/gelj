    private void jbSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSearchActionPerformed
        String name = jtfName.getText();
        String similarity = String.valueOf(jcbSimilarity.getSelectedItem());
        String linkage = String.valueOf(jcbLinkage.getSelectedItem());
        String tolerance = jtfTolerance.getText();

        DateFormat format = new SimpleDateFormat("yyyy-MM-dd");
        String fromDate = "";
        String toDate = "";
        if (jdpfrom.getDate() != null) {
            fromDate = format.format(jdpfrom.getDate());
        }
        if (jdpto.getDate() != null) {
            toDate = format.format(jdpto.getDate());
        }

        if (name.equals("") && similarity.equals(" ") && linkage.equals(" ")
                && tolerance.equals("")
                && fromDate.equals("") && toDate.equals("")) {
            JOptionPane.showMessageDialog(this, "Introduce some value to search", "", INFORMATION_MESSAGE, null);
        } else {
            int n = 0;
            if (!name.equals("")) {
                n++;
            }
            if (!similarity.equals(" ")) {
                n++;
            }
            if (!linkage.equals(" ")) {
                n++;
            }
            if (!tolerance.equals("")) {
                n++;
            }
            if (!(fromDate.equals(""))) {
                n++;
            }
            if (!(toDate.equals(""))) {
                n++;
            }

            ArrayList<Comparison> comparisons = searchcomparisons(studyid, name, similarity, linkage, tolerance, fromDate, toDate, n);
            if (comparisons.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Your search did not produce any result", "", INFORMATION_MESSAGE, null);
            } if(comparisons.size()==1){
//                se.setComparisons(comparisons);
//                se.updatecomparisons(false);
                 m.selectComparison(comparisons.get(0).getId());
                 dispose();
           }else{
               
//                se.setComparisons(comparisons);
//                se.updatecomparisons(false);
               
               String res = "Your search produced several results. The comparisons ";
               
               for(int i = 0;i <comparisons.size()-1;i++){
                   res = res + comparisons.get(i).getName() + ", ";
               }
               res = res + "and " + comparisons.get(comparisons.size()-1).getName() + " ";
               res = res + "satisfy your searching criteria.";
               
               JOptionPane.showMessageDialog(this, res, "", INFORMATION_MESSAGE, null); 
               
           }
        
            
            

        }


    }//GEN-LAST:event_jbSearchActionPerformed

