    private void jbCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbCreateActionPerformed
        String name = jtfName.getText();
        if (name == "") {
            JOptionPane.showMessageDialog(this, "Introduce the name of the comparison", "", INFORMATION_MESSAGE, null);
            return;
        }
        if(existscomparison(name,studyid)){
            JOptionPane.showMessageDialog(this, "There is already a comparison with that name", "", INFORMATION_MESSAGE, null);
            return;
        }

        String similarity = String.valueOf(jcbSimilarity.getSelectedItem());
        String linkage = String.valueOf(jcbLinkage.getSelectedItem());
        int tolerance = 4;
        try {
            tolerance = Integer.parseInt(jtfTolerance.getText());
            if (tolerance <= 0) {
                JOptionPane.showMessageDialog(this, "Introduce a positive number for the tolerance", "", INFORMATION_MESSAGE, null);
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Introduce a positive number for tolerance", "", INFORMATION_MESSAGE, null);
            return;
        }
        String comments = String.valueOf(jtacomments.getText());
        java.util.Calendar cal = java.util.Calendar.getInstance();
        java.util.Date utilDate = cal.getTime();
        java.sql.Date sqlDate = new Date(utilDate.getTime());

        Comparison c = new Comparison(lastComparisonid(), name, sqlDate, similarity, linkage, tolerance, comments, getStudy(studyid));
        insertComparison(c);
        se.updatecomparisons(true);
        dispose();
    }//GEN-LAST:event_jbCreateActionPerformed

  

