    private void jbSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSearchActionPerformed
        
        
       
        String name = jtfName.getText();
        String author = String.valueOf(jcbAuthor.getSelectedItem());
        String marker = String.valueOf(jcbMarker.getSelectedItem());
        DateFormat format = new SimpleDateFormat("yyyy-MM-dd");
        String fromDate=""; 
        String toDate="";
        if(jdpfrom.getDate()!=null){
            fromDate = format.format(jdpfrom.getDate());
        }
        if(jdpto.getDate()!=null){
            toDate = format.format(jdpto.getDate());
        }
        
        
        if(name.equals("") && author.equals("") && marker.equals("") &&
                fromDate.equals("") && toDate.equals("")){
           JOptionPane.showMessageDialog(this, "Introduce some value to search", "", INFORMATION_MESSAGE, null); 
        }else{
           int n = 0;
           if(!name.equals("")){n++;} 
           if(!author.equals("")){n++;}
           if(!marker.equals("")){n++;}
           if(!(fromDate.equals(""))){n++;}
           if(!(toDate.equals(""))){n++;}
             
           ArrayList<Experiment> experiments = searchexperiments(studyid,name,author,marker,fromDate,toDate,n);
           if(experiments.isEmpty()){
            JOptionPane.showMessageDialog(this, "Your search did not produce any result", "", INFORMATION_MESSAGE, null); 
           }if(experiments.size()==1){
//               se.setExperiments(experiments);
//               se.updateexperiments(false);
                 m.selectExperiment(experiments.get(0).getId());
                 dispose();
           }else{
               
//               se.setExperiments(experiments);
//               se.updateexperiments(false);
               
               String res = "Your search produced several results. The experiments ";
               
               for(int i = 0;i <experiments.size()-1;i++){
                   res = res + experiments.get(i).getName() + ", ";
               }
               res = res + "and " + experiments.get(experiments.size()-1).getName() + " ";
               res = res + "satisfy your searching criteria.";
               
               JOptionPane.showMessageDialog(this, res, "", INFORMATION_MESSAGE, null); 
               
           }
        
        
        
        }
        
        
        
        
        
        
        
    }//GEN-LAST:event_jbSearchActionPerformed

