    private void jbOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbOkActionPerformed
        if(jrbprevious.isSelected()){
            int idcomp = comparisons.get(jcbComparison.getSelectedIndex()).getId();
            insertComparisonLane(idcomp, lanes);  
            dispose();
        }else{
            int newcomp = ComparisonQueries.lastComparisonid();
            NewComparisonGUI nc = new NewComparisonGUI(this, true, studyid, se);
            nc.setVisible(true);
            int newcomp2 = ComparisonQueries.lastComparisonid();
            if(newcomp!=newcomp2){
                insertComparisonLane(newcomp, lanes);  
                dispose();            
            }
        }
    }//GEN-LAST:event_jbOkActionPerformed


