    public void updatestudies() {

        studies = getStudies(user);
        String[] names = {"Study", "Date", "Comments"};
        String[][] data = new String[studies.size()][3];

        // We update the table
        for (int i = 0; i < studies.size(); i++) {
            data[i][0] = studies.get(i).getName();
            data[i][1] = studies.get(i).getDate().toString();
            data[i][2] = studies.get(i).getComments();
        }

        // Operations to change the model, we disable the edition of the date
        DefaultTableModel model = new DefaultTableModel(data, names) {
            public boolean isCellEditable(int rowIndex, int mColIndex) {
                if (mColIndex == 1) {
                    return false;
                } else {
                    return true;
                }
            }
        };
        model.addTableModelListener(this);
        jTable.setModel(model);

    }

    @Override
    public void tableChanged(TableModelEvent e) {
        DefaultTableModel model = (DefaultTableModel) e.getSource();
        int row = e.getFirstRow();
        int column = e.getColumn();

        String cellValue = String.valueOf(jTable.getValueAt(row, column));

        if (column == 0) {
            if (existsstudy(cellValue, user)) {
                JOptionPane.showMessageDialog(this, "There is already a study with that name", "", INFORMATION_MESSAGE, null);
                updatestudies();
            } else {
                updateStudynameorcomments(studies.get(row).getId(), cellValue, true);
                updatestudies();
            }
        } else {
            updateStudynameorcomments(studies.get(row).getId(), cellValue, false);
            updatestudies();
        }

    }

