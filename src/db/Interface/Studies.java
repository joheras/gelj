    private void jbDeleteStudyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbDeleteStudyActionPerformed
        int row = jTable.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select a study first", "", INFORMATION_MESSAGE, null);
        } else {
            int reply = JOptionPane.showConfirmDialog(this, "Do you want to remove this study?", "Delete study", JOptionPane.YES_NO_OPTION);
            if (reply == JOptionPane.YES_OPTION) {
                int id = studies.get(row).getId();
                deletestudy(id);
                
                File folder = new File(System.getProperty("user.dir") + "/GelJDBImages/" + getUser(user).getUsername() + "/" + id);
                Utilities.deleteDir(folder);
                updatestudies();
            }

        }


    }//GEN-LAST:event_jbDeleteStudyActionPerformed

