    private void updatetext(){

        if(change){
        
        Roi roi = imp != null ? imp.getRoi() : null;
        TextRoi textRoi = roi != null && (roi instanceof TextRoi) ? (TextRoi) roi : null;
        String font = (String) jcbFont.getSelectedItem();
        int style = jcbStyle.getSelectedIndex();
        int fontSize = jSlider1.getValue();
        int angle = jSlider2.getValue();
        TextRoi.setFont(font, fontSize, style, true);
        TextRoi.setDefaultAngle(angle);
        String colour = (String)jcbColour.getSelectedItem();
        String fillc = (String)jcbBcgr.getSelectedItem();
       Color c = Colors.decode(colour,null);
       TextRoi.setColor(c);
       TextRoi.setDefaultAngle(angle);
       
       imp.getProcessor().setColor(c);
        Color fillColor = Colors.decode(fillc, null);
        if (textRoi != null) {
            textRoi.setAngle(angle);
            textRoi.setFillColor(fillColor);
            
            textRoi.setStrokeColor(c);
            textRoi.setAntialiased(true);
        }
        }
    }

