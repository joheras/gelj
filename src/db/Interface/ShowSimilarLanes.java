    public void updatelanes(ArrayList<LaneDBwithsimilarity> newlanes) {

        String[] names = {"Genus", "Species", "Strain Number", "Country", "MLST", "isMarker", "Experiment", "Comments", "Study", "User", "Similarity"};

        Object[][] data = new Object[newlanes.size()][names.length];

        // We update the table
        for (int i = 0; i < newlanes.size(); i++) {
            data[i][0] = newlanes.get(i).getLane().getGenus();
            data[i][1] = newlanes.get(i).getLane().getSpecies();
            data[i][2] = newlanes.get(i).getLane().getStrainNumber();
            data[i][3] = newlanes.get(i).getLane().getCountry();
            data[i][4] = newlanes.get(i).getLane().getMSLT();
            data[i][5] = newlanes.get(i).getLane().isIsMarker();
            data[i][6] = newlanes.get(i).getLane().getExperiment().getName();
            data[i][7] = newlanes.get(i).getLane().getComments();
            data[i][8] = newlanes.get(i).getLane().getExperiment().getStudy().getName();
            data[i][9] = newlanes.get(i).getLane().getExperiment().getStudy().getUser().getUsername();
            data[i][10] = newlanes.get(i).getSimilarity();
        }

        // Operations to change the model, we disable the edition of the date
        DefaultTableModel model = new DefaultTableModel(data, names) {
            public boolean isCellEditable(int rowIndex, int mColIndex) {
               return false;
            }
        };

        jtLanes.setModel(model);

    }

