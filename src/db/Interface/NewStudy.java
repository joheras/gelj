    private void newstudy() throws IOException {
        String name = jtfName.getText();
        String comments = jtaComments.getText();
        java.util.Calendar cal = java.util.Calendar.getInstance();
        java.util.Date utilDate = cal.getTime();
        Date date = new Date(utilDate.getTime());

        if (name.equals("")) {
            JOptionPane.showMessageDialog(this, "Introduce a name for the study");
            return;
        }

        if (edit) {
            Study s = getStudy(m.studyid);
            s.setName(name);
            s.setComments(comments);
            s.setDate(date);
            updateStudy(m.studyid, s);
            m.setTitle("GelJ (" + name + " )");
            dispose();
            return;
        }

        int id = lastStudyid();
        int user = m.getUserid();

        // Creating folders
        File folder0 = new File(System.getProperty("user.dir") + "/GelJDBImages/");

        if (!folder0.exists()) {
            folder0.mkdir();
        }

        String username = getUser(user).getUsername();
        File folderuser = new File(System.getProperty("user.dir") + "/GelJDBImages/"
                + id);

        if (!folderuser.exists()) {
            folderuser.mkdir();
        }

        File folder = new File(System.getProperty("user.dir") + "/GelJDBImages/" + id + "/" + username);
        folder.mkdir();
        File folderexp = new File(System.getProperty("user.dir") + "/GelJDBImages/" + id + "/" + username + "/experiments/");
        folderexp.mkdir();
        File foldercomp = new File(System.getProperty("user.dir") + "/GelJDBImages/" + id + "/" + username + "/comparisons/");
        foldercomp.mkdir();
        File folderunfinished = new File(System.getProperty("user.dir") + "/GelJDBImages/" + id + "/" + username + "/unfinished/");
        folderunfinished.mkdir();
        
        File folderunfinishedempty = new File(System.getProperty("user.dir") + "/GelJDBImages/" + id + "/" + username + "/unfinished/empty.txt");
        folderunfinishedempty.createNewFile();

        String path = System.getProperty("user.dir") + "/GelJDBImages/" + id + "/" + username;

        insertStudy(new Study(id, name, date, path, comments, getUser(user)));

        dispose();
        m.studyid = id;
        m.setTitle("GelJDB (" + name + ")");

    }

