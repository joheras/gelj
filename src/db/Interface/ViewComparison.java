    public ViewComparison(NewComparison nc, Comparison c) {
        initComponents();
        this.nc = nc;
        this.c = c;

        ArrayList<String> availablefields = nc.getNonSelectedFields();
        ArrayList<String> selectedfields = nc.getSelectedFields();

        DefaultListModel dmAvailable = new DefaultListModel();

        if (availablefields != null) {
            for (String s : availablefields) {
                dmAvailable.addElement(s);
            }
        }

        DefaultListModel dmSelected = new DefaultListModel();

        if (selectedfields != null) {
            for (String s : selectedfields) {
                dmSelected.addElement(s);
            }
        }
        
        String sim = nc.getSimilaritymethod();

        if(sim.equals("Pearson correlation") || sim.equals("Cosine coefficient") || sim.equals("Euclidean distance") || sim.equals("Manhattan distance")){
            jcbOutput.setModel(new javax.swing.DefaultComboBoxModel(new String[] {"Dendrogram + Images", "Dendrogram" }));
        }else{
            jcbOutput.setModel(new javax.swing.DefaultComboBoxModel(new String[] { "Dendrogram + Images + Bands", "Dendrogram + Images", "Dendrogram + Bands", "Dendrogram" }));
        }
        
        
        

        jlAvailable1.setModel(dmAvailable);
        jlAvailable1.addListSelectionListener(new AvailableListSelectionHandler());
        jlSelected.setModel(dmSelected);
        jlSelected.addListSelectionListener(new SelectedListSelectionHandler());
        this.setModal(true);

    }

