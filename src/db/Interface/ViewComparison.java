    private void jbShowActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbShowActionPerformed

        
        PleaseWait pw = new PleaseWait((JDialog)null, false);
        pw.setAlwaysOnTop(true);
        pw.toFront();
        DefaultListModel dmSelected = (DefaultListModel) jlSelected.getModel();
        DefaultListModel dmAvailable = (DefaultListModel) jlAvailable1.getModel();

        nc.setSelectedFields(new ArrayList<String>());
        nc.setNonSelectedFields(new ArrayList<String>());

        for (Object o : dmSelected.toArray()) {
            nc.getSelectedFields().add((String) o);
        }
        for (Object o : dmAvailable.toArray()) {
            nc.getNonSelectedFields().add((String) o);
        }

        if (nc.getSelectedFields().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Select at least a field to show in the dendrogram", "", INFORMATION_MESSAGE, null);
            return;
        }
        
        dispose();
//         PleaseWait pw = new PleaseWait(this, false);
//                pw.setVisible(true);
//                pw.toFront();
        try {
            String sim = nc.getSimilaritymethod(); 
            if(sim.equals("Pearson correlation") || sim.equals("Cosine coefficient") || sim.equals("Euclidean distance") || sim.equals("Manhattan distance")){
                 int output = jcbOutput.getSelectedIndex();
                 if(output==0){
                     output=1;
                 }else{
                     output=3;
                 }
                 generateDendrogram(c, output, nc.getSelectedFields(),jCheckBox1.isSelected(),pw,jcbinvert.isSelected());
            }else{
                 generateDendrogram(c, jcbOutput.getSelectedIndex(), nc.getSelectedFields(),jCheckBox1.isSelected(),pw,jcbinvert.isSelected());
            }     
        } catch (Exception ex) {
            Logger.getLogger(ViewComparison.class.getName()).log(Level.SEVERE, null, ex);
        }
//pw.dispose();
        
    }//GEN-LAST:event_jbShowActionPerformed

    private void jbAddFieldActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbAddFieldActionPerformed
        int[] tomove = jlAvailable1.getSelectedIndices();
        DefaultListModel dmSelected = (DefaultListModel) jlSelected.getModel();
        DefaultListModel dmAvailable = (DefaultListModel) jlAvailable1.getModel();

        if (tomove != null && tomove.length != 0) {
            for (int i : tomove) {
                dmSelected.addElement(dmAvailable.get(i));
                dmAvailable.remove(i);
            }

        }

    }//GEN-LAST:event_jbAddFieldActionPerformed

