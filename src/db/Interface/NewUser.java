    private void jButtonOkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonOkActionPerformed
        
        String username = jtfUsername.getText();
        String name = jtfName.getText();
        String surname = jtfSurname.getText();
        int poslab = jComboBox1.getSelectedIndex();
        int lab = labs.get(poslab).getId();
        
        if(username.equals("")){
            JOptionPane.showMessageDialog(this,"Introduce a username", "", INFORMATION_MESSAGE, null);
            return;
        }
        
        if(name.equals("")){
            JOptionPane.showMessageDialog(this,"Introduce a name", "", INFORMATION_MESSAGE, null);
            return;
        }
        
        if(surname.equals("")){
            JOptionPane.showMessageDialog(this,"Introduce a surname", "", INFORMATION_MESSAGE, null);
            return;
        }
        
        
        
        if(existssuser(username)){
            JOptionPane.showMessageDialog(this,"There is already a user with the username " + username, "", INFORMATION_MESSAGE, null);
                        return;
        }else{
            int id = lastUserid();
            User u = new User(id,username,name,surname,labs.get(poslab));
            insertUser(u);
        }
        
        this.dispose();
        su.updateusers();
        
    }//GEN-LAST:event_jButtonOkActionPerformed

