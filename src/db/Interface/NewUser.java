    public void updatelabs (){
        jComboBox1.removeAllItems();
        labs = getLabs();
        
        if (labs != null && labs.size()!=0) {
            for (Lab lab : labs) {
                jComboBox1.addItem(lab.getName() + " (" + lab.getCountry() + ")");
            }
        }else{
        jComboBox1.addItem("");
        }
        jComboBox1.addItem("<New Lab>");
        jComboBox1.setSelectedIndex(0);
    
    
    }
    

