    private void jbSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSearchActionPerformed
        
        
       
        String genus = String.valueOf(jcbGenus.getSelectedItem());
        String species = String.valueOf(jcbSpecies.getSelectedItem());
        String strainnumber = jtfStrainNumber.getText();
        String country = String.valueOf(jcbCountry.getSelectedItem());
        String MSLT = jtfMSLT.getText();
        String experiment = String.valueOf(jcbExperiment.getSelectedItem());
        DateFormat format = new SimpleDateFormat("yyyy-MM-dd");
        String fromDate=""; 
        String toDate="";
        if(jdpfrom.getDate()!=null){
            fromDate = format.format(jdpfrom.getDate());
        }
        if(jdpto.getDate()!=null){
            toDate = format.format(jdpto.getDate());
        }
        
        
        if(genus.equals("") && species.equals("") && strainnumber.equals("") &&
                country.equals("") && MSLT.equals("") && experiment.equals("") &&
                fromDate.equals("") && toDate.equals("")){
           JOptionPane.showMessageDialog(this, "Introduce some value to search", "", INFORMATION_MESSAGE, null); 
        }else{
           int n = 0;
           if(!genus.equals("")){n++;} 
           if(!species.equals("")){n++;}
           if(!strainnumber.equals("")){n++;}
           if(!country.equals("")){n++;} 
           if(!MSLT.equals("")){n++;}
           if(!experiment.equals("")){n++;}
           if(!(fromDate.equals(""))){n++;}
           if(!(toDate.equals(""))){n++;}
            
           ArrayList<LaneDB> lanes = searchlanes(m.studyid,genus,species,strainnumber,country,MSLT,experiment,fromDate,toDate,n);
           if(lanes.isEmpty()){
            JOptionPane.showMessageDialog(this, "Your search did not produce any result", "", INFORMATION_MESSAGE, null); 
           }else{
               m.setLanes(lanes);
               m.updatelanes(false);
           }
        
        
        
        }
        
        
        
        
        
        
        
    }//GEN-LAST:event_jbSearchActionPerformed

