    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String labname = jtfName.getText();
        String city = jtfCity.getText();
        String country = (String) jcbCountry.getSelectedItem();

        if (labname.equals("")) {
            JOptionPane.showMessageDialog(this, "Introduce the name of the lab", "", INFORMATION_MESSAGE, null);
            return;
        }

        if (city.equals("")) {
            JOptionPane.showMessageDialog(this, "Introduce the name of the city", "", INFORMATION_MESSAGE, null);
            return;
        }

        if (country.equals("")) {
                 JOptionPane.showMessageDialog(this, "Select the country of the lab");
            return;
        }

        if (existslab(labname, city, country)) {
                 JOptionPane.showMessageDialog(this, "There is already a lab called " + labname
                    + " in " + city + "(" + country + ")", "", INFORMATION_MESSAGE, null);

            return;
        } else {
            int id = lastLabid();
            Lab l = new Lab(id, labname, city, country);
            insertLab(l);
        }

        this.dispose();
        newuser.updatelabs();
    }//GEN-LAST:event_jButton1ActionPerformed

