    private void buttonDefineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonDefineActionPerformed
       
       this.dispose();
       boolean[] selectstandards = selectstandards(lanesnames(a.m.finallanes),
                        whatarestandardlanes(a.m.finallanes));
                if (selectstandards.length < 2) {
                    IJ.error("Select at least 2 lanes.");
           try {
               a.addreferencelanes();
           } catch (Exception ex) {
               Logger.getLogger(ReferenceLanes.class.getName()).log(Level.SEVERE, null, ex);
           }
                } else {
                    for (int i = 0; i < selectstandards.length; i++) {
                        a.m.finallanes[i].setIsstandard(selectstandards[i]);
                    }
                    a.autobanddetection();
                }
       // a.autoadjustbc();
        
    }//GEN-LAST:event_buttonDefineActionPerformed

