    private void buttonUndoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonUndoActionPerformed
        ImagePlus imp = WindowManager.getCurrentImage();
        IJ.run(imp, "Undo", "");
        undos--;
        if(undos==0){
            buttonUndo.setEnabled(false);
        }
        
        
        
        
        
    }//GEN-LAST:event_buttonUndoActionPerformed

    private void buttonInitialActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonInitialActionPerformed
      
        ImagePlus imp = WindowManager.getCurrentImage();
        ImagePlus imp2 = a.getInitialimage();
        String title = imp.getTitle();
        imp.changes=false;
        imp.close();
        imp2.setTitle(title);
        imp2.show();
        buttonInitial.setEnabled(false);
    }//GEN-LAST:event_buttonInitialActionPerformed


