    public EditOneLane( ImagePlus imp, BandManager bm,Main m) {
        super();
        initComponents();
        this.imp = imp;
        this.darkbg = darkbg;
        this.m=m;
        
        
        if(bm==null){
        this.bm.setbgcheckboxstate(darkbg);
//        bm.auto_detect();
        this.bm.setVisible(false);
        }else{
        this.bm = bm;
        }
        IJ.setTool("point");

        this.bm.updateShowAll();

        
        Dimension screenSize = Toolkit.getDefaultToolkit().getScreenSize();
        double width = screenSize.getWidth();
        setVisible(true);
        setLocation((int) width - 300, 0);
        imp.getWindow().setLocked(true);
        imp.getWindow().setAlwaysOnTop(true);
        this.setAlwaysOnTop(true);
        

       

    }

    
