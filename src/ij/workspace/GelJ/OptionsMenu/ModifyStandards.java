    private void jListStdsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jListStdsMouseClicked
        try {
            int pos = jListStds.getSelectedIndex();
            DefaultListModel listmodelstd = (DefaultListModel)jListStds.getModel();
            String name = (String)listmodelstd.getElementAt(pos);
            double[] values = readstandardfromfile(name);
            initjlist1();
            DefaultListModel listmodel = (DefaultListModel)jList1.getModel();
            listmodel.removeAllElements();
            
            for (double v : values){
                listmodel.addElement(v);
            }
            
        } catch (IOException ex) {
            Logger.getLogger(ModifyStandards.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        
        
        
    }//GEN-LAST:event_jListStdsMouseClicked

    private void jButtonSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSaveActionPerformed
        try {
            int pos = jListStds.getSelectedIndex();
            
            if (pos != -1){
            DefaultListModel listmodelstd = (DefaultListModel)jListStds.getModel();
            String name = (String)listmodelstd.getElementAt(pos);
            DefaultListModel listmodel = (DefaultListModel)jList1.getModel();
            double[] values = new double[listmodel.getSize()];
            
            for(int i = 0; i<listmodel.getSize();i++){
                values[i] = (Double)listmodel.get(i);
            }
            save_standard(name,values);
            }else{
                IJ.error("Select a standard first.");
            }
            } catch (FileNotFoundException ex) {
            Logger.getLogger(ModifyStandards.class.getName()).log(Level.SEVERE, null, ex);
        } catch (UnsupportedEncodingException ex) {
            Logger.getLogger(ModifyStandards.class.getName()).log(Level.SEVERE, null, ex);
        }
        
        
    }//GEN-LAST:event_jButtonSaveActionPerformed

    private void jButtonRecoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonRecoverActionPerformed
        ArrayList<String> availablestd = readstandardsremoved();
        
        if(availablestd.size()!=0){
            boolean[] res = recoverstandards(availablestd);
            if(res==null || res.length==0){
            }else{
                for (int i = 0; i<res.length;i++){
                    if(res[i]){
                        try {
                            recoverstandard(availablestd.get(i));
                        } catch (IOException ex) {
                            Logger.getLogger(ModifyStandards.class.getName()).log(Level.SEVERE, null, ex);
                        }
                    }
                }
                addstandards();
            }
            
        }else{
            IJ.error("You have not removed any standard previously.");
        }    
              
    }//GEN-LAST:event_jButtonRecoverActionPerformed

    
