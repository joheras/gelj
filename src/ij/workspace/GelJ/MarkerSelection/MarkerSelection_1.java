    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        close = false;
        if (lm.getCount() == 1) {
            lm.close();
            ImageWindow iw = imp.getWindow();
            iw.setLocked(false);
            BandManagerCanvas cc = new BandManagerCanvas(imp);
            ImageWindow iw2 = new ImageWindow(imp, cc);
            iw2.setLocked(true);
            iw.dispose();
            MarkerSelection_2 s = new MarkerSelection_2(imp, m, true,main);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "You must select a reference lane.");
        }

    }//GEN-LAST:event_jButton2ActionPerformed

