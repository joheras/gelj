    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        IJ.run(imp, "8-bit", "");
        this.setAlwaysOnTop(false);
        imp.getWindow().setAlwaysOnTop(false);
        if (lm.getCount() == 1) {
            JOptionPane.showMessageDialog(this, "You have already added one marker lane.\n"
                    + "Remove it, if you want to add a different one");
        } else {
            lm.runCommand("add");
            lm.fix_standard();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jComboBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jComboBox1ItemStateChanged
        this.setAlwaysOnTop(false);
        imp.getWindow().setAlwaysOnTop(false);
        int colour = jComboBox1.getSelectedIndex();
        Color c;
        switch (colour) {
            case BLUE:
                c = Color.BLUE;
                break;
            case RED:
                c = Color.RED;
                break;
            case GREEN:
                c = Color.GREEN;
                break;
            case MAGENTA:
                c = Color.MAGENTA;
                break;
            case CYAN:
                c = Color.CYAN;
                break;
            case YELLOW:
                c = Color.YELLOW;
                break;
            case ORANGE:
                c = Color.ORANGE;
                break;
            default:
                c = Color.BLUE;
                break;
        }
        lm.change_colour(c);


    }//GEN-LAST:event_jComboBox1ItemStateChanged

