    private void jcbMarkersActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jcbMarkersActionPerformed

        if(!firsttime){
        String marker = (String) jcbMarkers.getSelectedItem();

        try {
            double[] mws = readstandardfromfile(marker);
            DefaultListModel model = new DefaultListModel();
            jlmws.setModel(model);
            for (double d : mws) {
                model.addElement(d);
            }
            double[] pos = readstandardposfromfile(marker);
            double method = readstandardinfofromfile(marker)[2];
            CurveFitter cf = new CurveFitter(pos, mws);
            cf.doFit((int) method);
            plot(cf);
            ImagePlus imp = WindowManager.getCurrentImage();
            jXImageView1.setImage(imp.getImage());
            imp.close();

        } catch (IOException ex) {
            Logger.getLogger(ViewMarkers.class.getName()).log(Level.SEVERE, null, ex);
        }

        }

    }//GEN-LAST:event_jcbMarkersActionPerformed

