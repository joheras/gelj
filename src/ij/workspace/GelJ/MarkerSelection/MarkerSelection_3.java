    private void jComboBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jComboBox1ItemStateChanged
        int colour = jComboBox1.getSelectedIndex();
        Color c;
        switch (colour) {
            case BLUE:
                c = Color.BLUE;
                break;
            case RED:
                c = Color.RED;
                break;
            case GREEN:
                c = Color.GREEN;
                break;
            case MAGENTA:
                c = Color.MAGENTA;
                break;
            case CYAN:
                c = Color.CYAN;
                break;
            case YELLOW:
                c = Color.YELLOW;
                break;
            case ORANGE:
                c = Color.ORANGE;
                break;
            default:
                c = Color.BLUE;
                break;
        }
        bm.change_colour(c);
        bm.showAll(0);


    }//GEN-LAST:event_jComboBox1ItemStateChanged

