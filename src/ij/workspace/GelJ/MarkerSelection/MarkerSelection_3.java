    private void jbBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbBackActionPerformed
        close = false;
        int option = JOptionPane.showConfirmDialog(this, "If you go back, the current band selection\n will be lost, do you want to go back?", "Alert", JOptionPane.YES_NO_OPTION);
        if (option == JOptionPane.YES_OPTION) {
            imp.deleteRoi();
            bm.dispose();
            ImageWindow iw = imp.getWindow();
            LaneManagerCanvas cc = new LaneManagerCanvas(imp);
            ImageWindow iw2 = new ImageWindow(imp, cc);
            iw.hide();
            LaneManager lm = new LaneManager(m);
            MarkerSelection_1 s = new MarkerSelection_1(imp, lm,m,main);
            lm.delete_without_asking(false);
            Roi[] lanes = m.getLanes();
            if (lanes != null) {
                for (Roi lane : lanes) {
                    lm.addRoi(lane);
                }

                if (getstandardlanes(m.finallanes) != null) {
                    lm.fix_standards(roisfromlanes(getstandardlanes(m.finallanes)));
                }
            }
            lm.setLanesinfo(m.getLanesinfo());

            this.dispose();
        }


    }//GEN-LAST:event_jbBackActionPerformed

