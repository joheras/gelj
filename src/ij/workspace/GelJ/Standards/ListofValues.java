    public void addelements (double[] values){
        DefaultListModel listmodel = (DefaultListModel)jList1.getModel();
        for (double value : values){
            insertsort(listmodel,value);
        }
    }
    
    
    public double[] getelements(){
        DefaultListModel listmodel = (DefaultListModel)jList1.getModel();
        double[] res = new double[listmodel.getSize()];
        for(int i = 0;i<listmodel.getSize();i++){
            res[i] = (Double)listmodel.get(i);
        }
        return res;
    
    }
    
    
    private void insertsort (DefaultListModel listmodel, double value){
        boolean last = true;
        int i = 0;
        
        while (i<listmodel.getSize() & last){
            if ((Double)listmodel.elementAt(i)<value){
                last = false;
            }else{
                i++;
            }
        }
        
        if(last){
            listmodel.addElement(value);
        }else{
            listmodel.add(i, value);
        }
        
        
        
    
    
    }
    
    
    
